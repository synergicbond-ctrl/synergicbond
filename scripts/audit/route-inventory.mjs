// scripts/audit/route-inventory.mjs — Phase 0 baseline: machine-readable
// inventory of every route in app/, grouped by migration-map family.
//
//   node scripts/audit/route-inventory.mjs
//
// Writes docs/audit/route-inventory.json and docs/audit/route-inventory.md.
// Read-only over app/; deterministic output (stable ordering) so diffs are
// reviewable. Internal-link and navigation columns are heuristics computed by
// scanning static hrefs — see check-internal-links.mjs for the shared scan.

import fs from "node:fs";
import path from "node:path";
import { discoverRoutes, matchRoute } from "./route-discovery.mjs";
import { collectStaticHrefs } from "./check-internal-links.mjs";

const repoRoot = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const appDir = path.join(repoRoot, "app");
const outDir = path.join(repoRoot, "docs", "audit");

const routes = discoverRoutes(appDir);
const pages = routes.filter((r) => r.kind === "page");

// Static internal links across app/, components/, lib/ — used to mark which
// routes are actually linked, and which links come from navigation components.
const hrefs = collectStaticHrefs(repoRoot);
const linkedPatterns = new Map(); // pattern -> Set(sourceFile)
const navPatterns = new Map(); // pattern -> Set(sourceFile) from nav-ish files
const NAV_FILE = /nav|navbar|header|footer|menu|sidebar|tabbar/i;

for (const link of hrefs) {
  const route = matchRoute(link.path, routes);
  if (!route) continue;
  if (!linkedPatterns.has(route.pattern)) linkedPatterns.set(route.pattern, new Set());
  linkedPatterns.get(route.pattern).add(link.file);
  if (NAV_FILE.test(link.file)) {
    if (!navPatterns.has(route.pattern)) navPatterns.set(route.pattern, new Set());
    navPatterns.get(route.pattern).add(link.file);
  }
}

// /learn ↔ /notes counterpart candidates: same slug present in both trees.
// Deliberately reported as CANDIDATES needing author confirmation — slug
// equality is not content equivalence (migration map F1).
const learnSlugs = new Set(
  pages.filter((r) => r.pattern.startsWith("/learn/")).map((r) => r.pattern.split("/")[2])
);
const notesSlugs = new Set(
  pages.filter((r) => r.pattern.startsWith("/notes/")).map((r) => r.pattern.split("/")[2])
);
const counterpartCandidates = [...learnSlugs].filter((s) => s && notesSlugs.has(s)).sort();

const inventory = pages.map((r) => ({
  pattern: r.pattern,
  family: r.family,
  sourceFile: r.sourceFile,
  dynamic: r.dynamic,
  studentFacing: r.studentFacing,
  linkedInternally: linkedPatterns.has(r.pattern),
  linkedFromNavigation: navPatterns.has(r.pattern),
  counterpartCandidate:
    r.pattern.startsWith("/learn/") || r.pattern.startsWith("/notes/")
      ? counterpartCandidates.includes(r.pattern.split("/")[2]) || undefined
      : undefined,
}));

const byFamily = {};
for (const row of inventory) {
  byFamily[row.family] = byFamily[row.family] ?? [];
  byFamily[row.family].push(row);
}

const summary = {
  generatedAt: new Date().toISOString().slice(0, 10),
  totalRoutePatterns: routes.length,
  pageRoutes: pages.length,
  apiHandlerRoutes: routes.length - pages.length,
  studentFacingPages: inventory.filter((r) => r.studentFacing).length,
  byFamily: Object.fromEntries(
    Object.entries(byFamily)
      .map(([family, rows]) => [family, rows.length])
      .sort((a, b) => String(a[0]).localeCompare(String(b[0])))
  ),
  learnNotesCounterpartCandidates: counterpartCandidates,
  unlinkedStudentFacingPages: inventory
    .filter((r) => r.studentFacing && !r.linkedInternally && !r.dynamic)
    .map((r) => r.pattern),
};

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  path.join(outDir, "route-inventory.json"),
  JSON.stringify({ summary, routes: inventory }, null, 2) + "\n"
);

const md = [
  "# Route inventory — Phase 0 baseline",
  "",
  "Generated by `node scripts/audit/route-inventory.mjs` from the live `app/` tree.",
  "Regenerate after any route change; do not edit by hand.",
  "",
  `- Total route patterns: **${summary.totalRoutePatterns}** (${summary.pageRoutes} pages, ${summary.apiHandlerRoutes} API handlers)`,
  `- Student-facing pages: **${summary.studentFacingPages}**`,
  `- \`/learn\` ↔ \`/notes\` same-slug counterpart candidates (need author confirmation, not equivalence): ${
    counterpartCandidates.length ? counterpartCandidates.map((s) => `\`${s}\``).join(", ") : "none"
  }`,
  "",
  "## Pages by family",
  "",
  "| Pattern | Family | Dynamic | Linked internally | In navigation | Source |",
  "| --- | --- | --- | --- | --- | --- |",
  ...inventory.map(
    (r) =>
      `| \`${r.pattern}\` | ${r.family} | ${r.dynamic ? "yes" : ""} | ${
        r.linkedInternally ? "yes" : "no"
      } | ${r.linkedFromNavigation ? "yes" : ""} | \`${r.sourceFile}\` |`
  ),
  "",
  "## Unlinked static student-facing pages",
  "",
  "Implemented pages with no statically detectable internal link. **Not** a list of",
  "obsolete routes — deep links, redirects, notifications, and dynamically built",
  "hrefs are invisible to a static scan. Classify with traffic data (Phase 0",
  "baseline) before any decision.",
  "",
  ...(summary.unlinkedStudentFacingPages.length
    ? summary.unlinkedStudentFacingPages.map((p) => `- \`${p}\``)
    : ["- none"]),
  "",
].join("\n");

fs.writeFileSync(path.join(outDir, "route-inventory.md"), md);

console.log(
  `route-inventory: ${summary.pageRoutes} pages / ${summary.apiHandlerRoutes} handlers → docs/audit/route-inventory.{json,md}`
);
