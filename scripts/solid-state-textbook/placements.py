"""Where each animation goes in the textbook.

A placement is anchored to an exact heading in the combined chapter. `lab` placements embed the real Three.js
Crystal Lab at a structure/mode deep link. `widget` placements embed one of the small non-3D models
(defects, packing fractions, radius ratio, density), which complement the lab and never replace it.

`connect` is the sentence written for this location: why the model sits here and how it ties to the theory above it.
"""

def lab(heading, hash_, connect, title=None):
    return dict(kind="lab", heading=heading, hash=hash_, connect=connect, title=title)


def widget(heading, name, connect, **fields):
    return dict(kind="widget", heading=heading, widget=name, connect=connect, **fields)


